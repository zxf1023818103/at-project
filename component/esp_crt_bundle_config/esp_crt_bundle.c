/* esp_crt_check_signature() reaches the (private in 3.6) sig_md / sig fields of mbedtls_x509_crt. */
#define MBEDTLS_ALLOW_PRIVATE_ACCESS

#include <string.h>
#include <stdbool.h>
#include <stdio.h>
#include <sys/param.h>      /* MIN */

#include "esp_crt_bundle.h"

#include "mbedtls/pk.h"
#include "mbedtls/md.h"
#include "mbedtls/x509_crt.h"

/* Minimal logging shim (the upstream pulls esp_log/esp_check). Quiet by default; flip the
 * verbose levels on for debugging. The prefix matches the upstream TAG. */
#define CRTB_TAG "esp-x509-crt-bundle"
#define ESP_LOGE(tag, fmt, ...) printf("[%s] " fmt "\r\n", tag, ##__VA_ARGS__)
#define ESP_LOGI(tag, fmt, ...) printf("[%s] " fmt "\r\n", tag, ##__VA_ARGS__)
#define ESP_LOGD(tag, fmt, ...) do {} while (0)

/* Local replacement for CONFIG_MBEDTLS_CERTIFICATE_BUNDLE_MAX_CERTS. */
#define CRT_BUNDLE_MAX_CERTS 200

/*
    Format of certificate bundle (generated by gen_crt_bundle.py):
    n uint32 little-endian "offset" entries (one per cert, byte offset from the start of the
    bundle), immediately followed by the 1st..n-th certificate records. offsets[0] equals the
    size of the offset list, so cert count = offsets[0] / sizeof(uint32_t).

    Each certificate record:
        [length of subject name](u16, LE)
        [length of public key](u16, LE)
        [subject name DER](variable)
        [public key DER / SubjectPublicKeyInfo](variable)

    Records are sorted by subject name so a cert is found by issuer via binary search.
*/

#define CRT_NAME_LEN_OFFSET 0
#define CRT_KEY_LEN_OFFSET  (CRT_NAME_LEN_OFFSET + sizeof(uint16_t))
#define CRT_NAME_OFFSET     (CRT_KEY_LEN_OFFSET + sizeof(uint16_t))
#define CRT_HEADER_SIZE     CRT_NAME_OFFSET

static const char *TAG = CRTB_TAG;

/* a dummy certificate so cacert_ptr passes the non-NULL check during the handshake */
static const mbedtls_x509_crt s_dummy_crt;

/* The embedded bundle blob, generated into x509_crt_bundle.c by bin2c.py at build time. */
extern const unsigned char esp_crt_bundle_start[];
extern const unsigned int  esp_crt_bundle_len;

typedef const uint8_t *bundle_t;
typedef const uint8_t *cert_t;

static bundle_t s_crt_bundle;

static uint16_t get16_le(const uint8_t *ptr)
{
#if defined(__BYTE_ORDER__) && (__BYTE_ORDER__ == __ORDER_LITTLE_ENDIAN__)
    return *((const uint16_t *)ptr);
#else
    return (((uint16_t)ptr[1]) << 8) | ptr[0];
#endif
}

static uint16_t esp_crt_get_name_len(const cert_t cert)
{
    return get16_le(cert + CRT_NAME_LEN_OFFSET);
}

static const uint8_t *esp_crt_get_name(const cert_t cert)
{
    return cert + CRT_NAME_OFFSET;
}

static uint16_t esp_crt_get_key_len(const cert_t cert)
{
    return get16_le(cert + CRT_KEY_LEN_OFFSET);
}

static const uint8_t *esp_crt_get_key(const cert_t cert)
{
    return esp_crt_get_name(cert) + esp_crt_get_name_len(cert);
}

static uint16_t esp_crt_get_len(const cert_t cert)
{
    return CRT_HEADER_SIZE + esp_crt_get_name_len(cert) + esp_crt_get_key_len(cert);
}

static uint32_t esp_crt_get_cert_offset(const bundle_t bundle, const uint32_t index)
{
    return ((const uint32_t *)bundle)[index];
}

static uint32_t esp_crt_get_certcount(const bundle_t bundle)
{
    return esp_crt_get_cert_offset(bundle, 0) / sizeof(uint32_t);
}

static cert_t esp_crt_get_cert(const bundle_t bundle, const uint32_t index)
{
    return bundle + esp_crt_get_cert_offset(bundle, index);
}

/* Classic (non-PSA) signature check: parse the trusted root's public key, hash the child's
 * to-be-signed bytes, and verify the child's signature with mbedtls_pk_verify(). This is the
 * pre-PSA esp_crt_bundle algorithm; it builds on AmebaD's Mbed TLS 3.6.4 unchanged. */
static int esp_crt_check_signature(const mbedtls_x509_crt *child, const uint8_t *pub_key_buf, size_t pub_key_len)
{
    int ret = 0;
    mbedtls_pk_context pubkey;
    const mbedtls_md_info_t *md_info;
    unsigned char hash[MBEDTLS_MD_MAX_SIZE];

    mbedtls_pk_init(&pubkey);

    if ((ret = mbedtls_pk_parse_public_key(&pubkey, pub_key_buf, pub_key_len)) != 0) {
        ESP_LOGE(TAG, "PK parse failed with error 0x%x", -ret);
        goto cleanup;
    }

    md_info = mbedtls_md_info_from_type(child->sig_md);
    if (md_info == NULL) {
        ESP_LOGE(TAG, "Unknown message digest type: %d", child->sig_md);
        ret = MBEDTLS_ERR_X509_FEATURE_UNAVAILABLE;
        goto cleanup;
    }

    if ((ret = mbedtls_md(md_info, child->tbs.p, child->tbs.len, hash)) != 0) {
        ESP_LOGE(TAG, "Hash of certificate TBS failed with error 0x%x", -ret);
        goto cleanup;
    }

    if ((ret = mbedtls_pk_verify(&pubkey, child->sig_md, hash, mbedtls_md_get_size(md_info),
                                 child->sig.p, child->sig.len)) != 0) {
        ESP_LOGE(TAG, "PK verify failed with error 0x%x", -ret);
        goto cleanup;
    }

cleanup:
    mbedtls_pk_free(&pubkey);
    return ret;
}

static cert_t esp_crt_find_cert(const unsigned char *const issuer, const size_t issuer_len)
{
    if (issuer == NULL || issuer_len == 0) {
        return NULL;
    }

    int start = 0;
    int end = esp_crt_get_certcount(s_crt_bundle) - 1;
    int middle = (start + end) / 2;

    cert_t cert = NULL;
    size_t cert_name_len = 0;

    /* Binary search on the bundle's subject names (sorted ascending). */
    while (start <= end) {
        cert = esp_crt_get_cert(s_crt_bundle, middle);
        cert_name_len = esp_crt_get_name_len(cert);

        int cmp_res = memcmp(issuer, esp_crt_get_name(cert), MIN(issuer_len, cert_name_len));

        if (cmp_res == 0) {
            return cert;
        } else if (cmp_res < 0) {
            end = middle - 1;
        } else {
            start = middle + 1;
        }
        middle = (start + end) / 2;
    }

    return NULL;
}

/* Called for every certificate in the chain during verification. mbedTLS's chain builder marks
 * the top (untrusted) cert NOT_TRUSTED because the dummy CA chain matches nothing; this callback
 * catches that, looks the issuer up in the bundle, verifies the signature, and clears the flag. */
int esp_crt_verify_callback(void *buf, mbedtls_x509_crt *const crt, const int depth, uint32_t *const flags)
{
    (void)buf;
    (void)depth;
    const mbedtls_x509_crt *const child = crt;

    /* A trusted bundle root may use a weak hash; ignore that here (we already trust it). Keep
     * EXPIRED/FUTURE so real certificates still fail validity checks. */
    uint32_t flags_filtered = *flags & ~(MBEDTLS_X509_BADCERT_BAD_MD);

    if (flags_filtered != MBEDTLS_X509_BADCERT_NOT_TRUSTED) {
        return 0;
    }

    if (s_crt_bundle == NULL) {
        ESP_LOGE(TAG, "No certificates in bundle");
        return MBEDTLS_ERR_X509_FATAL_ERROR;
    }

    ESP_LOGD(TAG, "%u certificates in bundle", (unsigned)esp_crt_get_certcount(s_crt_bundle));

    cert_t cert = esp_crt_find_cert(child->issuer_raw.p, child->issuer_raw.len);

    if (cert != NULL) {
        const int ret = esp_crt_check_signature(child, esp_crt_get_key(cert), esp_crt_get_key_len(cert));
        if (ret == 0) {
            ESP_LOGI(TAG, "Certificate validated");
            *flags = 0;
            return 0;
        }
        ESP_LOGE(TAG, "Certificate matched but signature verification failed");
    } else {
        ESP_LOGI(TAG, "No matching trusted root certificate found");
    }

    /* The issuer wasn't in the bundle. A server may over-send the chain up to a root we already
     * trust whose OWN issuer is not in the bundle (e.g. AWS IoT presents up to "Starfield Services
     * Root CA - G2", whose issuer is the legacy "Starfield Class 2" we don't carry). If THIS cert's
     * subject + public key exactly match a bundle root, the server handed us a copy of a trust
     * anchor we hold, so trust it. The public-key match (not just the name) is what keeps this safe:
     * a forged cert reusing a trusted subject but a different key is rejected. */
    cert_t self = esp_crt_find_cert(child->subject_raw.p, child->subject_raw.len);
    if (self != NULL) {
        unsigned char keybuf[1024];
        int klen = mbedtls_pk_write_pubkey_der((mbedtls_pk_context *)&child->pk, keybuf, sizeof(keybuf));
        if (klen > 0 && (size_t)klen == esp_crt_get_key_len(self) &&
            memcmp(keybuf + sizeof(keybuf) - klen, esp_crt_get_key(self), klen) == 0) {
            ESP_LOGI(TAG, "Certificate validated (trusted root presented in server chain)");
            *flags = 0;
            return 0;
        }
    }

    ESP_LOGE(TAG, "Failed to verify certificate");
    return MBEDTLS_ERR_X509_CERT_VERIFY_FAILED;
}

/* Consistency checks on the bundle data: it really is an offset list + sorted cert records. */
static bool esp_crt_check_bundle(const uint8_t *const x509_bundle, const size_t bundle_size)
{
    if (x509_bundle == NULL || bundle_size <= (sizeof(uint32_t) + CRT_HEADER_SIZE)) {
        return false;
    }

    const uint32_t *offsets = (const uint32_t *)x509_bundle;

    if (offsets[0] == 0 || (offsets[0] % sizeof(uint32_t)) != 0) {
        return false;
    }
    if (offsets[0] >= bundle_size) {
        return false;
    }

    const uint32_t num_certs = esp_crt_get_certcount(x509_bundle);

    if (num_certs > CRT_BUNDLE_MAX_CERTS) {
        ESP_LOGE(TAG, "Cert bundle certificates exceed max allowed certificates");
        return false;
    }

    for (uint32_t i = 0; i < num_certs - 1; ++i) {
        const uint32_t off = offsets[i];
        cert_t cert = x509_bundle + off;
        const uint32_t expected_next_offset = off + esp_crt_get_len(cert);

        if (offsets[i + 1] != expected_next_offset || expected_next_offset >= bundle_size) {
            return false;
        }
    }

    return true;
}

static int esp_crt_bundle_init(const uint8_t *const x509_bundle, const size_t bundle_size)
{
    if (esp_crt_check_bundle(x509_bundle, bundle_size)) {
        s_crt_bundle = x509_bundle;
        return 0;
    }
    return -1;
}

/* Load the embedded bundle once. Returns 0 when s_crt_bundle is usable. */
static int esp_crt_bundle_ensure(void)
{
    if (s_crt_bundle != NULL) {
        return 0;
    }
    return esp_crt_bundle_init(esp_crt_bundle_start, esp_crt_bundle_len);
}

int esp_crt_bundle_attach(void *conf, mbedtls_x509_crt *trust_ca)
{
    int ret = esp_crt_bundle_ensure();
    if (ret != 0) {
        ESP_LOGE(TAG, "Failed to attach bundle");
        return ret;
    }

    if (conf) {
        mbedtls_ssl_config *ssl_conf = (mbedtls_ssl_config *)conf;
        mbedtls_ssl_conf_verify(ssl_conf, esp_crt_verify_callback, NULL);
        /* CA chain = the file/folder-loaded extra roots, so a server that chains to one of those is
         * trusted directly (the verify callback covers everything else via the bundle). When no
         * file roots were loaded, use the dummy so cacert_ptr passes the non-NULL handshake check. */
        mbedtls_ssl_conf_ca_chain(ssl_conf,
                                  trust_ca ? trust_ca : (mbedtls_x509_crt *)&s_dummy_crt, NULL);
    }
    return ret;
}

void esp_crt_bundle_detach(void *conf)
{
    s_crt_bundle = NULL;
    if (conf) {
        mbedtls_ssl_config *ssl_conf = (mbedtls_ssl_config *)conf;
        mbedtls_ssl_conf_verify(ssl_conf, NULL, NULL);
        mbedtls_ssl_conf_ca_chain(ssl_conf, NULL, NULL);
    }
}

int esp_crt_bundle_set(const uint8_t *x509_bundle, size_t bundle_size)
{
    return esp_crt_bundle_init(x509_bundle, bundle_size);
}

int esp_crt_bundle_verify_chain(mbedtls_x509_crt *chain, mbedtls_x509_crt *trust_ca,
                                const char *cn, uint32_t *flags)
{
    int ret = esp_crt_bundle_ensure();
    if (ret != 0) {
        ESP_LOGE(TAG, "Bundle not available");
        return MBEDTLS_ERR_X509_FATAL_ERROR;
    }
    /* trust_ca = the file/folder-loaded extra roots (or the dummy if none): a server chaining to
     * one of those is trusted directly; everything else is checked against the bundle by the
     * verify callback. */
    return mbedtls_x509_crt_verify(chain,
                                   trust_ca ? trust_ca : (mbedtls_x509_crt *)&s_dummy_crt, NULL,
                                   cn, flags, esp_crt_verify_callback, NULL);
}

uint32_t esp_crt_bundle_count(void)
{
    if (esp_crt_bundle_ensure() != 0) {
        return 0;
    }
    return esp_crt_get_certcount(s_crt_bundle);
}

uint32_t esp_crt_bundle_blob_size(void)
{
    return esp_crt_bundle_len;
}
