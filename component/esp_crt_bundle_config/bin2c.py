#!/usr/bin/env python3
# Wrap a raw binary blob (the generated x509 CA bundle) into a C source with stable
# external symbols, so it embeds into the AmebaD image as .rodata without objcopy /
# `ld -r -b binary` / INCBIN (none of which the AmebaD build uses today).
#
#   python3 bin2c.py x509_crt_bundle x509_crt_bundle.c
#
# (an explicit output path — not stdout — because CMake's add_custom_command runs without a shell,
# so `> file` redirection would not work.) Emits:
#   const unsigned char esp_crt_bundle_start[];   // the bundle bytes
#   const unsigned int  esp_crt_bundle_len;       // byte count
import sys

def main():
    if len(sys.argv) != 3:
        sys.stderr.write('usage: bin2c.py <blob> <out.c>\n')
        return 2
    with open(sys.argv[1], 'rb') as f:
        data = f.read()
    with open(sys.argv[2], 'w') as out:
        out.write('/* Auto-generated by bin2c.py from the Mozilla CA root bundle. Do not edit. */\n')
        out.write('const unsigned char esp_crt_bundle_start[] = {\n')
        for i in range(0, len(data), 16):
            out.write('    ' + ''.join('0x%02x, ' % b for b in data[i:i + 16]).rstrip() + '\n')
        out.write('};\n')
        out.write('const unsigned int esp_crt_bundle_len = %d;\n' % len(data))
    return 0

if __name__ == '__main__':
    sys.exit(main())
