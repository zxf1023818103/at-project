#!/usr/bin/env python3
"""Native cross-Host migration tests; no chip SDK, firmware build or hardware.

Both Hosts compile separately with their real headers. The exact shared SMP
source overlay is generated by the same CMake function used by all platforms.
"""
import os
from pathlib import Path
import subprocess

root=Path(__file__).resolve().parents[3]
out=root/'build/ble-store-tests/interop';out.mkdir(parents=True,exist_ok=True)
bd=root/'component/bluedroid_config'
host=bd/'esp-idf/components/bt/host/bluedroid'
common=bd/'esp-idf/components/bt/common'
lfs=root/'component/littlefs_config/littlefs'
store=root/'component/ble_store_config'
nbstore=root/'component/nimble_config/store'

def run(args):
    result=subprocess.run([str(arg) for arg in args],cwd=root)
    if result.returncode: raise SystemExit(result.returncode)

def includes(paths):
    return ['-I'+str(p) for p in paths]

run(['cmake','-DBLUEDROID_HOST_ROOT='+str(host),'-DBOND_OUTPUT_DIR='+str(out),
     '-P',bd/'bond_overlays.cmake'])
base=['cc','-std=gnu11','-g','-O1','-Wall','-Wextra','-Wno-unused-parameter',
      '-fsanitize=address,undefined','-ffunction-sections','-fdata-sections',
      '-DLFS_THREADSAFE','-DLFS_NO_MALLOC','-DLFS_NAME_MAX=32',
      '-DLFS_NO_DEBUG','-DLFS_NO_WARN','-DLFS_NO_ERROR']
shared=includes([store/'tests/include',store,lfs])
# Include directories from the vendored Host, without any chip port headers.
bflags=shared+includes([bd/'include',bd/'esp-idf/components/esp_common/include'])
bflags+=includes(sorted({p for tree in (host,common) for p in tree.rglob('include')}
                       | {host/'api/include/api',common/'api/include/api'}))
bflags+=['-DBLUEDROID_PORT_CONFIG_HEADER="bond_test_config.h"','-include','string.h']
objects=[]
for source in [store/'tests/interop_bluedroid.c',bd/'nvs_lfs.c',common/'osi/config.c',common/'osi/list.c',out/'smp_act_bonds.c']:
    target=out/(source.stem+'.o')
    # ASan registers the global SMP action table, retaining all unused actions.
    # Only this TU is uninstrumented, allowing gc-sections to isolate the real
    # reconnect action. Storage adapters and config parser remain instrumented.
    extra=['-fno-sanitize=all'] if source.stem=='smp_act_bonds' else []
    run(base+bflags+extra+['-c',source,'-o',target]);objects.append(target)
for version in ['nimble','upstream-1.10.0']:
    nb=root/'component/nimble_config'/version
    if not (nb/'nimble/host/src/ble_store.c').exists():
        raise SystemExit('Missing vendored NimBLE: '+str(nb))
    flags=shared+includes([nbstore,nb/'porting/npl/linux/include',nb/'porting/nimble/include',
        nb/'nimble/include',nb/'nimble/host/include',nb/'nimble/host/src',nb/'nimble/host/services/gatt/include',nb/'nimble/transport/include'])
    target=out/('interop-'+version)
    run(base+flags+[store/'tests/interop_nimble.c',nb/'nimble/host/src/ble_store.c',
        nbstore/'ble_store_littlefs.c',store/'ble_bond_store.c',store/'lfs_blob.c',lfs/'lfs.c',lfs/'lfs_util.c',
        *objects,'-Wl,--gc-sections','-pthread','-o',target])
    os.environ['ASAN_OPTIONS']='detect_leaks=0'
    print('Testing '+version,flush=True);run([target])
