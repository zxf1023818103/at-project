#!/usr/bin/env python3
"""
Generate (once) the Ed25519 keypair used by SBOOT=ON to sign image2, and emit the
public key as a C header for the on-device sboot self-test.

This runs at CONFIGURE time (before the KM4 build) so sboot_pk.h exists when
sboot_cli.c compiles; build_image_all.py later signs image2 with the SAME private
key (so the embedded public key matches the signature the device verifies).

  - private key: build/sboot/sboot_priv.pem   (gitignored; a THROWAWAY proof key,
                 NOT a production/HSM signing key)
  - public key : build/sboot/sboot_pk.h       (static const uint8_t sboot_pk[32])

AmebaD secure boot is Ed25519 (the boot ROM's ed25519_verify_signature); the raw
32-byte public key is exactly what would be burned to eFuse 0x1A0 in a real enable.
Idempotent: regenerates nothing if the key already exists.
"""
import os
import sys

from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
from cryptography.hazmat.primitives import serialization

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
SBOOT_DIR = os.path.join(REPO, "build", "sboot")
PRIV_PEM = os.path.join(SBOOT_DIR, "sboot_priv.pem")
PK_HEADER = os.path.join(SBOOT_DIR, "sboot_pk.h")


def load_or_create_key():
    os.makedirs(SBOOT_DIR, exist_ok=True)
    if os.path.exists(PRIV_PEM):
        with open(PRIV_PEM, "rb") as f:
            return serialization.load_pem_private_key(f.read(), password=None)
    key = Ed25519PrivateKey.generate()
    pem = key.private_bytes(
        encoding=serialization.Encoding.PEM,
        format=serialization.PrivateFormat.PKCS8,
        encryption_algorithm=serialization.NoEncryption(),
    )
    with open(PRIV_PEM, "wb") as f:
        f.write(pem)
    print("[sboot] generated throwaway Ed25519 key: %s" % PRIV_PEM)
    return key


def raw_pubkey(key):
    return key.public_key().public_bytes(
        encoding=serialization.Encoding.Raw,
        format=serialization.PublicFormat.Raw,
    )


def emit_header(pk):
    rows = []
    for i in range(0, 32, 8):
        rows.append("    " + " ".join("0x%02x," % b for b in pk[i:i + 8]))
    body = "\n".join(rows)
    text = (
        "/* Auto-generated by sboot_keygen.py - DO NOT EDIT.\n"
        " * Ed25519 public key matching the SBOOT=ON image2 signature; the on-device\n"
        " * `sboot` self-test verifies against this (the bytes that would be eFuse 0x1A0). */\n"
        "#ifndef SBOOT_PK_H\n"
        "#define SBOOT_PK_H\n"
        "static const unsigned char sboot_pk[32] = {\n"
        "%s\n"
        "};\n"
        "#endif /* SBOOT_PK_H */\n" % body
    )
    # only rewrite if changed, to avoid spurious recompiles
    if os.path.exists(PK_HEADER):
        with open(PK_HEADER) as f:
            if f.read() == text:
                return
    with open(PK_HEADER, "w") as f:
        f.write(text)
    print("[sboot] wrote %s" % PK_HEADER)


def main():
    key = load_or_create_key()
    pk = raw_pubkey(key)
    emit_header(pk)
    print("[sboot] public key = %s" % pk.hex())


if __name__ == "__main__":
    sys.exit(main())
