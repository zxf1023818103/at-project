#!/usr/bin/env bash
set -euo pipefail
APP_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
REPO_DIR="$(cd -- "$APP_DIR/../.." && pwd)"
WORK_DIR="${TL3238_BUILD_DIR:-$REPO_DIR/build/tl3238}"
TL3238_ENABLE_BLE="${TL3238_ENABLE_BLE:-ON}"
TL3238_ENABLE_CS="${TL3238_ENABLE_CS:-$TL3238_ENABLE_BLE}"
TL3238_ENABLE_OTA="${TL3238_ENABLE_OTA:-$TL3238_ENABLE_BLE}"
TL3238_ENABLE_COC="${TL3238_ENABLE_COC:-$TL3238_ENABLE_BLE}"
TL3238_OTA_BUILD_NUMBER="${TL3238_OTA_BUILD_NUMBER:-1}"
source "$REPO_DIR/component/telink_sdk/tools/toolchain.sh"
cmake -S "$APP_DIR" -B "$WORK_DIR/firmware" -G Ninja \
    -DTL3238_TOOLCHAIN="$TL3238_TOOLCHAIN" \
    -DTL3238_NIMBLE_ROOT="$REPO_DIR/component/nimble_config/upstream-1.10.0" \
    -DTL3238_ENABLE_BLE="$TL3238_ENABLE_BLE" -DTL3238_ENABLE_CS="$TL3238_ENABLE_CS" \
    -DTL3238_ENABLE_OTA="$TL3238_ENABLE_OTA" -DTL3238_ENABLE_COC="$TL3238_ENABLE_COC" \
    -DTL3238_OTA_BUILD_NUMBER="$TL3238_OTA_BUILD_NUMBER" "$@"
cmake --build "$WORK_DIR/firmware" --parallel
sha256sum "$WORK_DIR/firmware/tl3238_freertos.bin"
